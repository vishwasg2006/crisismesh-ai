-- Optional: the server creates all of this automatically on first start.
-- Run manually only if you want to see / pre-create the schema.
CREATE DATABASE IF NOT EXISTS crisismesh CHARACTER SET utf8mb4;
USE crisismesh;

-- Document tables (id + JSON document). Same shape for each collection.
CREATE TABLE IF NOT EXISTS cm_settlements (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_routes      (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_resources   (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_reports     (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_incidents   (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_plans       (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_sync_queue  (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cm_kv          (id VARCHAR(64) PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);

-- Append-only event log (every report, plan, network change, sync, approval)
CREATE TABLE IF NOT EXISTS event_log (
  seq     BIGINT AUTO_INCREMENT PRIMARY KEY,
  ts      BIGINT NOT NULL,
  type    VARCHAR(64) NOT NULL,
  node    VARCHAR(64) NOT NULL,
  payload JSON NULL,
  INDEX idx_type (type)
);
